def _workdir(scenario_run_id: str) -> Path:
    return RUNS_DIR / f"{scenario_run_id}-worldscene"


def _available_runs() -> list[str]:
    base = POC_DIR / "scenario-runs"
    return sorted(p.name for p in base.iterdir() if (p / "scenario-report.json").is_file())


def run_world_scene(scenario_run_id: str, hitl_approved: bool = False) -> dict[str, Any]:
    """Execute the utrecht-world-scene recipe for one poc/scenario-runs/<id>: build world-scene-specs.json (engine GeoJSON refs + gated Marble prompts) in deep-agents/runs/. poc/ itself is never modified. Call render_world_scene_demo afterwards for the visual demo."""
    import os

    if os.environ.get("NLDT_REQUIRE_INTAKE") == "1":
        from tools.artifacts import submitted_request

        if submitted_request() is None:
            journal.append(
                "error",
                "utrecht",
                "world-scene-build GEWEIGERD: geen gesubmiteerde, schema-geldige aanvraag — delegeer eerst intake (submit_request)",
            )
            raise ValueError(
                "Geen gesubmiteerde aanvraag: in ketenmodus moet de intake-specialist eerst "
                "submit_request aanroepen (schema-geldig OpportunityMapRequest) voordat de "
                "world scene gebouwd mag worden."
            )
    src = POC_DIR / "scenario-runs" / scenario_run_id
    if not (src / "scenario-report.json").is_file():
        raise FileNotFoundError(
            f"Unknown scenario run '{scenario_run_id}'. Runs with a scenario-report: "
            + ", ".join(_available_runs())
        )
    journal.append(
        "tool_call", "utrecht", f"run_world_scene('{scenario_run_id}') — world-scene-build"
    )
    work = _workdir(scenario_run_id)
    work.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src / "scenario-report.json", work / "scenario-report.json")
    if (src / "scenarios").is_dir():
        shutil.copytree(src / "scenarios", work / "scenarios", dirs_exist_ok=True)

    if str(POC_DIR) not in sys.path:
        sys.path.insert(0, str(POC_DIR))
    from pipeline.world_scene import write_world_scene_bundle

    bundle_path = write_world_scene_bundle(work, hitl_approved=hitl_approved)
    bundle = json.loads(bundle_path.read_text(encoding="utf-8"))
    journal.append(
        "tool_result",
        "utrecht",
        f"world-scene-specs.json built: {bundle['specCount']} spec(s) for {scenario_run_id}",
        viz={"kind": "worldscene", "runId": scenario_run_id},
    )
    return {
        "scenarioRunId": scenario_run_id,
        "bundlePath": str(bundle_path),
        "specCount": bundle["specCount"],
        "specs": [
            {
                "id": s["id"],
                "scenarioId": s["scenarioId"],
                "track": s["track"],
                "deltaKm2": s["headlineDeltaKm2"],
                "deltaPct": s["headlineDeltaPct"],
                "provenance": s["provenanceBasis"]["type"],
                "grounding": s["groundingStamp"],
                "marbleEnabled": s["marble"]["enabled"],
            }
            for s in bundle["specs"]
        ],
        "nextStep": "call render_world_scene_demo to produce the visual demo",
    }


def render_world_scene_demo(scenario_run_id: str) -> dict[str, Any]:
    """Render the interactive Leaflet demo (demo.html) from a built world-scene bundle: control vs scenario GeoJSON overlays per spec with headline deltas, provenance notes and gated Marble prompts. Run run_world_scene first. Returns the demo file path."""
    work = _workdir(scenario_run_id)
    bundle_path = work / "world-scene-specs.json"
    if not bundle_path.is_file():
        raise FileNotFoundError(f"No bundle for '{scenario_run_id}' — run run_world_scene first.")

    bundle = json.loads(bundle_path.read_text(encoding="utf-8"))
    data: dict[str, Any] = {}
    cards: list[str] = []
    for s in bundle["specs"]:
        control = json.loads((work / "scenarios" / "CONTROL.geojson").read_text(encoding="utf-8"))
        scen_path = work / "scenarios" / f"{s['scenarioId']}.geojson"
        scenario = json.loads(scen_path.read_text(encoding="utf-8")) if scen_path.is_file() else control
        data[s["id"]] = {"control": control, "scenario": scenario}
        delta = s["headlineDeltaKm2"]
        cls = "neg" if delta < 0 else "pos"
        cards.append(
            f"<div class='spec' data-id='{s['id']}'>"
            f"<div class='badge'>{s['id']}</div>"
            + ("<span class='badge gated'>Marble gated</span>" if not s["marble"]["enabled"] else "")
            + f"<div class='delta {cls}'>{delta:+.2f} km² ({s['headlineDeltaPct']:+.2f}%)</div>"
            f"<div class='note'>{s['mutationSummary']} · provenance: {s['provenanceBasis']['type']} · {s['groundingStamp']}</div>"
            f"<details><summary>Marble prompt (gated)</summary><div class='note'>{s['marblePrompt']}</div></details>"
            "</div>"
        )

    leaflet_css, leaflet_js = leaflet_tags()
    html = _PAGE.format(
        run_id=scenario_run_id,
        spec_count=bundle["specCount"],
        spec_cards="\n".join(cards),
        payload=json.dumps(data),
        leaflet_css=leaflet_css,
        leaflet_js=leaflet_js,
    )
    demo_path = work / "demo.html"
    demo_path.write_text(html, encoding="utf-8")
    journal.append(
        "tool_result", "utrecht", f"demo.html rendered → {demo_path}"
    )
    return {
        "demoPath": str(demo_path),
        "specCount": bundle["specCount"],
        "openWith": f"open {demo_path}",
    }
