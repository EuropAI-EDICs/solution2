"""Utrecht Plane B world-scene tools: execute the utrecht-world-scene recipe
(world-scene-build process) and render the visual demo.

Inputs are copied into deep-agents/runs/<id>-worldscene/ and the build runs
there, so the canonical poc/scenario-runs directories are never modified.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path
from typing import Any

import journal
from vizassets import leaflet_tags

HERE = Path(__file__).resolve().parents[1]
REPO_ROOT = HERE.parent
POC_DIR = REPO_ROOT / "poc"
RUNS_DIR = HERE / "runs"

